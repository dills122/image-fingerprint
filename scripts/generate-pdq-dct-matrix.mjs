import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const REFERENCE_COMMIT = 'baefb4ed67b6cdc1d4c82dbaef858d50866ac424';
const VECTOR_ID = 'dct-identity-basis-gray-64x64';
const MATRIX_LENGTH = 16 * 64;
const DEFAULT_FIXTURE = resolve('__tests__/fixtures/pdq/stage-vectors.json');
const DEFAULT_OUTPUT = resolve('src/core/algorithms/pdq/dct-matrix.ts');

const parseArguments = (arguments_) => {
  const allowed = new Set(['--fixture', '--output']);
  const parsed = new Map();
  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];
    if (argument === '--') {
      continue;
    }
    if (!allowed.has(argument)) {
      throw new Error(`Unknown argument: ${argument}`);
    }
    if (parsed.has(argument)) {
      throw new Error(`Duplicate argument: ${argument}`);
    }
    if (index + 1 >= arguments_.length || arguments_[index + 1].startsWith('--')) {
      throw new Error(`${argument} requires a value`);
    }
    parsed.set(argument, arguments_[index + 1]);
    index += 1;
  }
  return parsed;
};

const arguments_ = parseArguments(process.argv.slice(2));
const fixturePath = resolve(arguments_.get('--fixture') ?? DEFAULT_FIXTURE);
const outputPath = resolve(arguments_.get('--output') ?? DEFAULT_OUTPUT);
const corpus = JSON.parse(await readFile(fixturePath, 'utf8'));
const vector = corpus.vectors?.find(({ id }) => id === VECTOR_ID);
const source = vector?.source;
const bits = vector?.expected?.dctMatrixBits;

if (corpus.schemaVersion !== 1
  || corpus.algorithm !== 'pdq-v1'
  || corpus.oracle?.commit !== REFERENCE_COMMIT
  || vector?.format !== 'gray8'
  || vector.width !== 64
  || vector.height !== 64
  || source?.encoding !== 'base64'
  || !Array.isArray(bits)
  || bits.length !== MATRIX_LENGTH
  || bits.some((value) => !Number.isInteger(value) || value < 0 || value > 0xffff_ffff)) {
  throw new Error(`Invalid ${VECTOR_ID} matrix fixture in ${fixturePath}`);
}

const sourceBytes = Buffer.from(source.data, 'base64');
const sourceSha256 = createHash('sha256').update(sourceBytes).digest('hex');
if (sourceBytes.length !== 64 * 64 || sourceSha256 !== source.sha256) {
  throw new Error(`Invalid ${VECTOR_ID} source bytes in ${fixturePath}`);
}
for (let y = 0; y < 64; y += 1) {
  for (let x = 0; x < 64; x += 1) {
    const expected = x === y ? 1 : 0;
    if (sourceBytes[y * 64 + x] !== expected) {
      throw new Error(`Invalid ${VECTOR_ID} identity value at (${x}, ${y})`);
    }
  }
}

const hex = bits.map((value) => value.toString(16).padStart(8, '0')).join('');
const chunks = hex.match(/.{1,96}/g);
if (chunks === null) {
  throw new Error(`Missing ${VECTOR_ID} matrix bits in ${fixturePath}`);
}
const stringLines = chunks.map((chunk) => `  '${chunk}',`).join('\n');
const sourceCode = `// Generated by scripts/generate-pdq-dct-matrix.mjs from the pinned Meta oracle.\n`
  + `// Fixture: ${VECTOR_ID}; commit: ${REFERENCE_COMMIT}.\n`
  + `const PDQ_DCT_MATRIX_LENGTH = ${MATRIX_LENGTH};\n\n`
  + 'const PDQ_DCT_MATRIX_BITS_HEX = [\n'
  + `${stringLines}\n`
  + "].join('');\n\n"
  + '/** @internal Decodes the exact float32 coefficient bits frozen by the normative oracle. */\n'
  + 'export const createPdqDctMatrix = (): Float32Array => {\n'
  + '  const matrix = new Float32Array(PDQ_DCT_MATRIX_LENGTH);\n'
  + '  const bitBuffer = new ArrayBuffer(Uint32Array.BYTES_PER_ELEMENT);\n'
  + '  const bitView = new DataView(bitBuffer);\n'
  + '  for (let index = 0; index < PDQ_DCT_MATRIX_LENGTH; index += 1) {\n'
  + '    const bitOffset = index * 8;\n'
  + '    const bits = Number.parseInt(\n'
  + '      PDQ_DCT_MATRIX_BITS_HEX.slice(bitOffset, bitOffset + 8),\n'
  + '      16,\n'
  + '    );\n'
  + '    bitView.setUint32(0, bits);\n'
  + '    matrix[index] = bitView.getFloat32(0);\n'
  + '  }\n'
  + '  return matrix;\n'
  + '};\n';

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, sourceCode, 'utf8');
process.stdout.write(`Wrote ${bits.length} PDQ DCT coefficient bits to ${outputPath}\n`);
